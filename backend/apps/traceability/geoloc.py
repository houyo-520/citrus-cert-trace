# 预编译成 (network, 省, 市, 运营商) 列表，供最长前缀匹配
_NETWORKS = []
for _prefix, _prov, _city, _isp in _CN_SEGMENTS:
    try:
        _NETWORKS.append((ipaddress.ip_network(_prefix), _prov, _city, _isp))
    except ValueError:
        continue
# 按前缀长度降序，保证最长前缀优先匹配
_NETWORKS.sort(key=lambda x: x[0].prefixlen, reverse=True)

# 内网 / 保留地址段（不对外解析，直接标记为本机/内网）
_PRIVATE_NETWORKS = [
    ipaddress.ip_network("10.0.0.0/8"),
    ipaddress.ip_network("172.16.0.0/12"),
    ipaddress.ip_network("192.168.0.0/16"),
    ipaddress.ip_network("127.0.0.0/8"),
    ipaddress.ip_network("169.254.0.0/16"),
    ipaddress.ip_network("100.64.0.0/10"),   # CGNAT 运营商级 NAT
    ipaddress.ip_network("::1/128"),
]


def _is_private(ip: ipaddress.IPv4Address) -> bool:
    return any(ip in net for net in _PRIVATE_NETWORKS)


def resolve(ip_str: str) -> dict:
    """
    把来源 IP 解析成地理位置信息。

    返回 dict：
      {
        "ip": "1.2.3.4",          # 规范化后的 IP
        "province": "四川",        # 省 / 直辖市
        "city": "成都",            # 市
        "isp": "电信",             # 运营商
        "location": "四川 成都",    # 组合展示串（省 + 市）
        "is_internal": False,      # 是否内网/本机
      }
    解析失败绝不上抛，永远返回一个可展示的结构（登录主流程不能被 IP 定位拖垮）。
    """
    ip_str = (ip_str or "").strip()
    # xff 可能带端口、多段，统一只取第一段并去空白
    ip_str = ip_str.split(",")[0].strip()

    result = {
        "ip": ip_str or "",
        "province": "",
        "city": "",
        "isp": "",
        "location": "",
        "is_internal": False,
    }

    try:
        ip = ipaddress.ip_address(ip_str)
    except ValueError:
        # 空串或非法 IP（如 "unknown"）
        result["location"] = "未知"
        return result

    # 内网 / 回环 / 本机
    if ip.version == 4 and _is_private(ip):
        result["is_internal"] = True
        if ip.is_loopback:
            result["location"] = "本机"
            result["province"], result["city"] = "本机", "本机"
        else:
            result["location"] = "内网"
            result["province"], result["city"] = "内网", "内网"
        return result

    # 公网 IPv4：最长前缀匹配
    if ip.version == 4:
        for net, prov, city, isp in _NETWORKS:
            if ip in net:
                result["province"] = prov
                result["city"] = city
                result["isp"] = isp
                result["location"] = f"{prov} {city}"
                return result

    # IPv6 或未命中前缀表 → 未知
    result["location"] = "未知地区"
    return result


